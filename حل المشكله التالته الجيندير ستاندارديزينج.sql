-- ============================================================
-- PROBLEM 03: GENDER STANDARDIZATION
-- ============================================================
-- الهدف:
-- اكتشاف القيم غير الموحدة في عمود Gender،
-- ومعرفة عدد مرات ظهور كل قيمة،
-- ثم توحيد القيم التي تمثل نفس المعنى.
--
-- المشكلة التي اكتشفناها:
-- Male   → 103,066
-- Female → 94,938
-- M      → 1,495
--
-- اكتشفنا أن M هي اختصار لـ Male،
-- ولذلك سنقوم بتحويل M إلى Male.
-- ============================================================



-- ============================================================
-- STEP 1: عرض البيانات
-- ============================================================
-- نعرض البيانات الموجودة في جدول raw_patient
-- حتى نأخذ نظرة عامة على شكل البيانات
-- والأعمدة والقيم الموجودة فيها.
--
-- هذه الخطوة استكشافية فقط ولا تقوم بأي تعديل.

SELECT *
FROM raw_patient;



-- ============================================================
-- STEP 2: اكتشاف جميع قيم Gender
-- ============================================================
-- GROUP BY Gender:
-- يجمع الـrecords حسب قيمة Gender.
--
-- COUNT(*):
-- يحسب عدد الـrecords الموجودة لكل قيمة.
--
-- ORDER BY total_count DESC:
-- يرتب القيم من الأكثر ظهورًا إلى الأقل.
--
-- الهدف:
-- اكتشاف هل يوجد أكثر من representation لنفس الـGender.

SELECT
    Gender,
    COUNT(*) AS total_count
FROM raw_patient
GROUP BY Gender
ORDER BY total_count DESC;



-- ============================================================
-- STEP 3: فحص قيمة M بشكل مباشر
-- ============================================================
-- بعد اكتشاف أن M موجودة في البيانات،
-- قمنا بعرض بعض الـrecords التي تحتوي على M.
--
-- الهدف:
-- التأكد من أن M مستخدمة بالفعل كقيمة لـGender
-- وليست قيمة لها معنى مختلف.
--
-- LIMIT 20:
-- نعرض أول 20 record فقط حتى لا نعرض الـ1,495 record كلها.

SELECT *
FROM raw_patient
WHERE Gender = 'M'
LIMIT 20;



-- ============================================================
-- STEP 4: مقارنة M مع Male
-- ============================================================
-- هنا نقارن بين:
-- M
-- Male
--
-- الهدف:
-- معرفة حجم كل قيمة قبل عملية الـStandardization.
--
-- WHERE Gender IN:
-- يختار فقط records التي تحتوي على M أو Male.

SELECT
    Gender,
    COUNT(*) AS total_count
FROM raw_patient
WHERE Gender IN ('M', 'Male')
GROUP BY Gender;



-- ============================================================
-- STEP 5: التحقق من وجود مسافات أو اختلافات مخفية
-- ============================================================
-- استخدمنا CONCAT لإظهار قيمة Gender بين [].
--
-- السبب:
-- أحيانًا تكون البيانات تحتوي على مسافات مخفية مثل:
--
-- 'Male'
-- 'Male '
-- ' M'
--
-- وهذه القيم قد تبدو متشابهة بصريًا،
-- لكنها تعتبر Values مختلفة في البيانات.
--
-- بعد الفحص وجدنا:
-- [Male]
-- [Female]
-- [M]
--
-- وبالتالي لا توجد مسافات زائدة أو Values مخفية.

SELECT
    CONCAT('[', Gender, ']') AS gender_value,
    COUNT(*) AS total_count
FROM raw_patient
GROUP BY Gender
ORDER BY total_count DESC;



-- ============================================================
-- STEP 6: STANDARDIZATION
-- ============================================================
-- بعد التحليل تأكدنا أن:
--
-- M = Male
--
-- لذلك نقوم بتوحيد الـrepresentation
-- وتحويل كل M إلى Male.
--
-- UPDATE:
-- يقوم بتعديل البيانات فعليًا.
--
-- WHERE Gender = 'M':
-- يضمن أننا نعدل فقط الـ1,495 records
-- التي تحتوي على M.
--
-- لا يتم حذف أي record.
-- نحن فقط نغير قيمة Gender.

UPDATE raw_patient
SET Gender = 'Male'
WHERE Gender = 'M';

-- Sample records containing the 'M' abbreviation for validation
SELECT *
FROM raw_patient
WHERE Gender = 'M'
LIMIT 20;

-- ============================================================
-- STEP 7: التحقق من النتيجة بعد الـUPDATE
-- ============================================================
-- بعد عملية الـStandardization نعيد نفس التحليل
-- للتأكد من أن M اختفت وأن عدد Male زاد.
--
-- النتيجة المتوقعة:
--
-- Male   → 104,561
-- Female → 94,938
--
-- Total → 199,499
--
-- لاحظ:
-- إجمالي عدد الـrecords لم يتغير.
-- الذي تغير فقط هو representation الخاصة بـGender.

SELECT
    Gender,
    COUNT(*) AS total_count
FROM raw_patient
GROUP BY Gender
ORDER BY total_count DESC;



-- ============================================================
-- STEP 8: FINAL VALIDATION
-- ============================================================
-- نتأكد بشكل مباشر أن مفيش أي record ما زالت
-- تحتوي على Gender = 'M'.
--
-- Expected Result:
-- remaining_M = 0
--
-- إذا كانت النتيجة 0، فهذا يعني أن عملية
-- Gender Standardization تمت بنجاح.

SELECT
    COUNT(*) AS remaining_M
FROM raw_patient
WHERE Gender = 'M';



-- ============================================================
-- FINAL RESULT
-- ============================================================
-- قبل التنظيف:
--
-- Male   → 103,066
-- Female → 94,938
-- M      → 1,495
--
-- عملية التنظيف:
--
-- M → Male
--
-- بعد التنظيف:
--
-- Male   → 104,561
-- Female → 94,938
-- M      → 0
--
-- إجمالي الـrecords:
-- 199,499 قبل وبعد التنظيف.
--
-- النتيجة:
-- أصبح لدينا تمثيل موحد للـGender
-- بدون فقدان أي records.
-- ============================================================